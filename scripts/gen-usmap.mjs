// Generates src/data/us-map.ts: SVG path data for every state (pre-projected
// AlbersUSA, 975x610 viewport) plus projected x/y for each National-page pin.
// Precomputed so the shipped bundle carries no d3 and the map prerenders to
// static HTML. Re-run after editing PINS:  node scripts/gen-usmap.mjs
import fs from "node:fs";
import { createRequire } from "node:module";
import { geoAlbersUsa, geoPath } from "d3-geo";
import * as topojson from "topojson-client";
import { presimplify, simplify, quantile } from "topojson-simplify";

const require = createRequire(import.meta.url);

// us-atlas "albers" files are projected with exactly this (see its README).
const projection = geoAlbersUsa().scale(1300).translate([487.5, 305]);

// City pins (lon, lat). State-level pins use the state centroid.
const CITY_PINS = [
  { label: "Phoenix", state: "AZ", lon: -112.074, lat: 33.448 },
  { label: "Los Angeles", state: "CA", lon: -118.243, lat: 34.052 },
  { label: "Santa Barbara", state: "CA", lon: -119.698, lat: 34.421 },
  { label: "Las Vegas", state: "NV", lon: -115.139, lat: 36.172 },
  { label: "Park City", state: "UT", lon: -111.498, lat: 40.646 },
  { label: "Georgetown", state: "TX", lon: -97.677, lat: 30.633 },
  { label: "Greensburg", state: "KS", lon: -99.293, lat: 37.603 },
];
const STATE_PINS = ["CO", "OR", "ID", "WA", "MT", "FL"];

// FIPS -> USPS for the states we touch.
const FIPS = {
  "04": "AZ", "06": "CA", "32": "NV", "49": "UT", "08": "CO", "48": "TX",
  "20": "KS", "41": "OR", "16": "ID", "53": "WA", "30": "MT", "12": "FL",
};
const ACTIVE = new Set(Object.values(FIPS));

let topo = require("us-atlas/states-albers-10m.json");
// Light simplification: coastline detail is invisible at 975px wide.
topo = presimplify(topo);
topo = simplify(topo, quantile(topo, 0.25));

const path = geoPath(); // identity: geometry is already projected
const states = topojson.feature(topo, topo.objects.states).features;

const round = (n) => Math.round(n * 10) / 10;
const stateOut = states
  .map((f) => ({
    id: f.id,
    usps: FIPS[f.id] ?? null,
    name: f.properties.name,
    d: path(f).replace(/(\d+\.\d+)/g, (m) => round(+m).toString()),
    centroid: path.centroid(f).map(round),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const pins = [];
for (const p of CITY_PINS) {
  const xy = projection([p.lon, p.lat]);
  if (!xy) throw new Error(`pin outside projection: ${p.label}`);
  pins.push({ label: p.label, state: p.state, kind: "city", x: round(xy[0]), y: round(xy[1]) });
}
for (const usps of STATE_PINS) {
  const s = stateOut.find((x) => x.usps === usps);
  if (!s) throw new Error(`state not found: ${usps}`);
  pins.push({ label: s.name, state: usps, kind: "state", x: s.centroid[0], y: s.centroid[1] });
}

const nation = topojson.feature(topo, topo.objects.nation);
const nationD = path(nation).replace(/(\d+\.\d+)/g, (m) => round(+m).toString());

const out = `// GENERATED by scripts/gen-usmap.mjs. Do not edit by hand.
// AlbersUSA projection, 975x610 viewport (us-atlas states-albers-10m).
export const MAP_W = 975;
export const MAP_H = 610;

export interface MapState { id: string; usps: string | null; name: string; d: string; active: boolean }
export interface MapPin { label: string; state: string; kind: "city" | "state"; x: number; y: number }

export const NATION_D = ${JSON.stringify(nationD)};

export const STATES: MapState[] = ${JSON.stringify(
  stateOut.map((s) => ({ id: s.id, usps: s.usps, name: s.name, d: s.d, active: !!s.usps && ACTIVE.has(s.usps) })),
  null,
  0
)};

export const PINS: MapPin[] = ${JSON.stringify(pins, null, 2)};
`;

fs.mkdirSync("src/data", { recursive: true });
fs.writeFileSync("src/data/us-map.ts", out);
console.log(`wrote src/data/us-map.ts (${(out.length / 1024).toFixed(1)} KB, ${stateOut.length} states, ${pins.length} pins)`);
